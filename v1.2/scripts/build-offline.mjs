import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const order=['schema','sleep','model','legacy-model','sleep-comparison','sleep-diary','sleep-diary-ui','copy','marginal','demo','comparison','guide','workspace','navigation','app'];
export async function buildOffline(entry='app'){
  if(!order.includes(entry))throw new Error('Unknown entry');
  const seen=new Set(),chunks=[];
  for(const name of order.slice(0,order.indexOf(entry)+1)){
    let source=await readFile(resolve(root,`src/${name}.js`),'utf8');
    const exports=new Set();
    source=source.replace(/^import\s*\{\s*([\w\s,]+)\s*\}\s*from\s*['"]\.\/([\w-]+)\.js['"];?/gm,(_,members,dep)=>{
      if(!seen.has(dep))throw new Error(`Dependency order ${name} -> ${dep}`);
      return `const {${members.replace(/\s+as\s+/g,': ')}}=__modules[${JSON.stringify(dep)}];`;
    });
    source=source.replace(/^export (const|let|function) (\w+)/gm,(_,kind,id)=>{exports.add(id);return `${kind} ${id}`;});
    if(/^\s*(import|export)\s/m.test(source))throw new Error(`Unsupported syntax in ${name}`);
    chunks.push(`__modules[${JSON.stringify(name)}]=(()=>{\n${source}\nreturn {${[...exports].join(',')}};\n})();`);seen.add(name);
  }
  return `// Generated from v1.2/src; do not edit this file directly.\n(()=>{\n'use strict';\nconst __modules=Object.create(null);\n${chunks.join('\n')}\nreturn __modules[${JSON.stringify(entry)}];\n})();\n`;
}
if(process.argv[1] && pathToFileURL(resolve(process.argv[1])).href===import.meta.url){await writeFile(resolve(root,'app.offline.js'),await buildOffline());console.log('v1.2 offline bundle built');}
